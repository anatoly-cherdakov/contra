  const installed = new WeakMap();
  const asSigned = value => value < 128 ? value : value - 256;
  // JSNES emits packed BGR pixels. Slots 4..6 shade the tank using the
  // original muscle contours. Slots 7..9 draw the beanie and folded cuff.
  const colors = [
    ["141720", "262b38", "424958", "242932", "495262", "11141b"],
    ["10264e", "2053a3", "4082ce", "173771", "3670b0", "142c57"]
  ].map(row => row.map(hex => parseInt(hex.match(/../g).reverse().join(""), 16)));

  // Decode the same bank-1 metasprites as the game's OAM builder. Shared
  // tails follow a pointer and cancel the one-pixel firing recoil.
  function readPoses(bank) {
    const word = offset => bank[offset] | (bank[offset + 1] << 8);
    const poses = [];
    for (let code = 2; code <= 0x91; code++) {
      if (!(code <= 6 || (code >= 8 && code <= 0x17) ||
            (code >= 0x19 && code <= 0x1d) || (code >= 0x50 && code <= 0x58) ||
            code === 0x91)) continue;
      let pos = word(0x3030 + 2 * (code - 1)) - 0x8000;
      const count = bank[pos++];
      const parts = [];
      let recoil = true;
      for (let part = 0; part < count; part++) {
        if (bank[pos] === 0x80) {
          pos = word(pos + 1) - 0x8000;
          recoil = false;
        }
        const dy = asSigned(bank[pos++]);
        const tile = bank[pos++];
        const attr = bank[pos++];
        const dx = asSigned(bank[pos++]);
        parts.push({dx, dy, tile, attr, recoil});
      }
      poses[code] = parts;
    }
    return poses;
  }

  window.applyPlayers = function applyPlayers(nes) {
    const ppu = nes.ppu;
    const bank = nes.rom.rom[1];
    const previous = installed.get(ppu);
    if (previous && previous.tiles === ppu.ptTile) return;
    if (bank[0x3030] !== 0xce || bank[0x3031] !== 0xb1)
      throw new Error("Player costumes require the Contra (USA) sprite table.");

    const poses = readPoses(bank);
    const owner = new Int8Array(64).fill(-1);
    const costumes = [0, 0];
    // The game writes OAM in rotating $c4-byte steps, with P2 before P1.
    // Scan backwards to disambiguate players even when perfectly overlapped.
    function identifyPlayers() {
      const mem = nes.cpu.mem;
      owner.fill(-1);
      for (let player = 0; player < 2; player++) {
        const code = mem[0x300 + player];
        const parts = poses[code];
        if (!parts) continue;
        costumes[player] = Number(code >= 0x50 && code <= 0x58);
        const flags = mem[0x34e + player];
        for (const part of parts) {
          const recoil = Number(part.recoil && Boolean(flags & 8));
          const dy = part.dy + recoil;
          const x = mem[0x334 + player] + (flags & 64 ? -8 - part.dx : part.dx);
          const y = (mem[0x31a + player] + (flags & 128 ? -16 - dy : dy)) & 255;
          if (x < 0 || x > 255 || y >= 239) continue;
          const flips = (flags ^ part.attr) & 0xc0;
          const palette = (flags & 4 ? flags : part.attr) & 3;
          let offset = mem[0x35];
          for (let step = 0; step < 64; step++) {
            offset = (offset - 0xc4) & 255;
            const slot = offset >>> 2;
            const addr = 0x200 + offset;
            if (owner[slot] < 0 && mem[addr] === y && mem[addr+1] === part.tile &&
                (mem[addr+2] & 0xc3) === (palette | flips) && mem[addr+3] === x) {
              owner[slot] = player;
              break;
            }
          }
        }
      }
    }

    // loadROM keeps the PPU but rebuilds its tile array. Keep one DMA
    // wrapper and direct it to the ownership map for the current tiles.
    const state = previous || {};
    state.tiles = ppu.ptTile;
    state.onDMA = page => {
      if (page === 2) identifyPlayers();
      else owner.fill(-1);
    };
    if (!previous) {
      const dma = ppu.sramDMA;
      ppu.sramDMA = function(page) {
        const result = dma.call(this, page);
        state.onDMA(page);
        return result;
      };
      installed.set(ppu, state);
    }

    // Keep the native tile renderer for sprite priority, flipping and clipping.
    // Only its per-call pixel and palette inputs are substituted.
    for (let id = 0; id < 256; id++) {
      if (!(masks[0][id] || masks[1][id] || contraFaces.tiles[0][id] || contraFaces.tiles[1][id])) continue;
      const tile = ppu.ptTile[id];
      const render = tile.render;
      const pixels = new Uint8Array(64);
      const palette = new Uint32Array(74);
      tile.render = function(buffer, x1, y1, x2, y2, x, y, base, original, h, v, slot, priority) {
        const player = owner[slot];
        const mask = player >= 0 && masks[costumes[player]][id];
        const face = player >= 0 && !costumes[player] && contraFaces.tiles[player][id];
        if (!mask && !face) return render.apply(this, arguments);
        const orientation = Number(Boolean(h)) + 2 * Number(Boolean(v));
        const source = this.pix;
        for (let i = 0; i < 64; i++) {
          if (face && face[i]) {
            pixels[i] = 10 + i;
            palette[10 + i] = 0x1000000 + (face[i]-1)*4 + orientation;
            continue;
          }
          const ink = mask ? mask.charCodeAt(i) - 48 : 0;
          const pixel = source[i];
          pixels[i] = ink === 1 ? (pixel ? pixel + 3 : 0) : ink ? ink + 5 : pixel;
        }
        for (let i = 0; i < 4; i++) palette[i] = original[base + i];
        palette.set(colors[player], 4);
        this.pix = pixels;
        try {
          return render.call(this, buffer, x1, y1, x2, y2, x, y, 0, palette, h, v, slot, priority);
        } finally {
          this.pix = source;
        }
      };
    }
  };
